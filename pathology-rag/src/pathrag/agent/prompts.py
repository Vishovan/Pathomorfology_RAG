# ----------------------------------------------------------------------------- поиск изображений
def image_results_text(query: str, images: list[dict[str, Any]]) -> str:
    lines = ["### 🖼️ Результаты поиска микропрепаратов и WSI-слайдов\n", f"**Запрос:** {query}\n"]
    if not images:
        lines.append("По данному запросу не найдено подходящих микропрепаратов в базе данных.")
    for i, img in enumerate(images, 1):
        stain, mag = img.get("stain", ""), img.get("magnification", "")
        wsi_url = img.get("wsi_url") or img.get("image_url", "")
        lines += [
            f"#### #{i} {img.get('title', 'Микропрепарат')}",
            f"- **Орган / ткань:** {img.get('organ', '')}",
            f"- **Окраска:** `{stain}` | **Увеличение:** `{mag}`",
            f"- **Диагноз:** {img.get('diagnosis', '')}",
            f"- **Морфологическое описание:** {img.get('caption', '')}",
            f"- **Источник:** {img.get('source_name') or img.get('source_id', '')}",
        ]
        if wsi_url:
            lines.append(f"- 🔬 **Интерактивный Whole Slide Image:** [Открыть слайд в цифровом вьюере]({wsi_url})")
        lines.append("")
    return "\n".join(lines)


