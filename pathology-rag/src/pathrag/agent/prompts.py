def _doc_source_label(d: dict[str, Any]) -> str:
    return f"{d.get('source')} ({d.get('page_reference')})" if d.get("page_reference") else d.get("source", "")


def clinical_prompt_from_docs(query: str, docs: list[dict[str, Any]]) -> str:
    clinical_context = "\n\n---\n\n".join(
        f"[ЧАНК {i}]\nНазвание документа: {d.get('title')}\nИсточник: {_doc_source_label(d)}\nТекст:\n{d.get('text')}"
        for i, d in enumerate(docs, 1)
    )
    return (
        f"Вопрос пользователя:\n{query}\n\n"
        f"=== ФРАГМЕНТЫ БАЗЫ ЗНАНИЙ (ЧАНКИ ИЗ ВЕРИФИЦИРОВАННЫХ РУКОВОДСТВ) ===\n"
        f"{clinical_context}\n"
        f"====================================================================\n\n"
        f"ИНСТРУКЦИЯ ДЛЯ ВРАЧА-ПАТОЛОГОАНАТОМА:\n"
        f"1. Сформулируйте профессиональный, логичный и клинически выверенный ответ на вопрос пользователя.\n"
        f"2. ВАЖНО: Ваш ответ должен быть СИНТЕЗИРОВАН ИЗ ПРЕДОСТАВЛЕННЫХ ЧАНКОВ. Сопоставьте информацию из разных фрагментов: выделите ключевые диагностические критерии, процентные пороги (0, 1+, 2+, 3+ или отсечки Ki-67), правила дифференциальной диагностики и алгоритмы подтверждающего тестирования (FISH, SISH).\n"
        f"3. Не копируйте текст чанков целиком — проведите глубокий экспертный синтез и обобщение.\n"
        f"4. Обязательно сошлитесь в тексте на номера источников [1], [2], подтверждающие каждое диагностическое утверждение.\n"
        f"5. Оформите ответ в Markdown со структурированными подразделами, списками и выделением ключевых терминов жирным шрифтом."
    )


def clinical_prompt_from_external(query: str, lit: list[dict[str, Any]], web: list[dict[str, Any]]) -> str:
    parts = [f"Публикация ({it.get('source_type', 'PubMed')}): {it.get('title')}\n{it.get('summary', '')}" for it in lit]
    parts += [f"Веб-источник: {it.get('title')}\n{it.get('snippet', '')}" for it in web]
    ext_str = "\n\n".join(parts)
    ext_banner = f"=== МАТЕРИАЛЫ ВНЕШНЕГО НАУЧНОГО ПОИСКА ===\n{ext_str}\n==========================================\n\n" if ext_str else ""
    return (
        f"Клинический вопрос врача:\n{query}\n\n"
        f"{ext_banner}"
        f"ИНСТРУКЦИЯ ДЛЯ ВРАЧА-ПАТОЛОГОАНАТОМА:\n"
        f"1. Дайте точный, научно обоснованный и структурированный ответ на вопрос по патологической анатомии и гистологии.\n"
        f"2. Подробно опишите патогенез, макро- и микроскопическую картину, дифференциальную диагностику и применяемые окраски.\n"
        f"3. Оформите ответ в Markdown с четкими подразделами, маркированными списками и акцентами на ключевых терминах."
    )


def _verification_tips(query: str) -> list[str]:
    q = query.lower()
    if "her2" in q:
        return [
            "- При получении неопределенного статуса **HER2 2+ (equivocal)** обязательным этапом является подтверждающая **FISH / SISH гибридизация** in situ для оценки амплификации гена ERBB2.",
            "- Опухоли с ИГХ 1+ или ИГХ 2+ при отсутствии амплификации по FISH классифицируются как **HER2-low**, что открывает возможность таргетной терапии новыми конъюгатами (T-DXd).",
        ]
    if "ki-67" in q or "люминальн" in q:
        return [
            "- Индекс пролиферации **Ki-67** оценивается стандартизированным методом в зонах максимальной активности («hot spots») с подсчетом не менее 500-1000 клеток.",
            "- Пороговое значение **< 14-20%** разграничивает Люминальный А и Люминальный В подтипы рака молочной железы с различным прогнозом и чувствительностью к химиотерапии.",
        ]
    return ["- Для окончательной верификации диагноза сопоставьте световую микроскопию (окраска H&E) с панелью специфических ИГХ-маркеров и данными анамнеза."]


def clinical_fallback(query: str, docs: list[dict[str, Any]], lit: list[dict[str, Any]], web: list[dict[str, Any]]) -> str:
    """Экспертный RAG-синтез без LLM: прямое извлечение фрагментов базы знаний."""
    lines = [
        "### 🔬 Клинико-морфологическое заключение (Автономный RAG-синтез)\n",
        "> ℹ️ *Внешний инференс LLM сейчас недоступен (не указан ключ или превышен лимит). Ответ сформирован прямым алгоритмическим извлечением релевантных данных из базы знаний.*\n",
        f"**Клинический запрос:** {query}\n",
    ]
    if docs:
        lines.append("#### 1. Диагностические критерии и выдержки из верифицированных источников:\n")
        for i, doc in enumerate(docs, 1):
            ref = doc.get("page_reference", "")
            ref_str = f" · {ref}" if ref else ""
            lines.append(f"##### 📌 [{i}] {doc.get('title', '')} ({doc.get('source', '')}{ref_str})")
            lines.append(f"{doc.get('text', '')}\n")
        lines.append("#### 2. Экспертные рекомендации по тактике верификации:")
        lines += _verification_tips(query)
    else:
        lines.append("В локальной базе знаний точных фрагментов не обнаружено. Выполнен поиск по открытым научным источникам.\n")

    if lit or web:
        lines.append("\n#### 3. Внешние научные публикации и ссылки:")
        lines += [f"- [{it.get('title')}]({it.get('url')}) — *{it.get('source_type')}*" for it in lit]
        lines += [f"- [{it.get('title')}]({it.get('url')}) — *Веб-источник*" for it in web]

    lines.append(
        "\n---\n💡 **Рекомендация:** Для генерации развернутого ответа нейросетью Llama 3.3 70B укажите бесплатный "
        "API-ключ **Groq** в левой панели (получить бесплатно за 30 секунд на [console.groq.com](https://console.groq.com))."
    )
    return "\n".join(lines)
